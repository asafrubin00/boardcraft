// One-off generator for the dotted world map (src/components/worldmap/landDots.ts).
// Samples Natural Earth 1:110m land on an even grid; the map itself ships as
// plain data, so nothing here is needed at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const COLS = 150, LAT_TOP = 78, LAT_BOTTOM = -56;
const step = 360 / COLS;
const ROWS = Math.round((LAT_TOP - LAT_BOTTOM) / step);
const rows = [];
let n = 0;
for (let r = 0; r < ROWS; r++) {
  let line = '';
  const lat = LAT_TOP - (r + 0.5) * step;
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + (c + 0.5) * step;
    const on = geoContains(land, [lon, lat]);
    line += on ? '1' : '0';
    if (on) n++;
  }
  rows.push(line);
}
writeFileSync('src/components/worldmap/landDots.ts',
`// Generated by scripts/build-world-dots.mjs from Natural Earth 1:110m land (public domain).
export const MAP = { cols: ${COLS}, rows: ${ROWS}, latTop: ${LAT_TOP}, latBottom: ${LAT_BOTTOM} } as const;
export const LAND_ROWS: string[] = ${JSON.stringify(rows, null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '",\n]')};
`);
console.log(COLS, ROWS, n);
